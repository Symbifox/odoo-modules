    # ------------------------------------------------------------------
    # Computes
    # ------------------------------------------------------------------
    @api.depends("is_template", "active", "date_from", "date_to")
    def _compute_state(self):
        now = fields.Datetime.now()
        for absence in self:
            if absence.is_template:
                absence.state = "template"
            elif not absence.active:
                absence.state = "off"
            elif absence.date_from and absence.date_from > now:
                absence.state = "planned"
            elif absence.date_to and absence.date_to < now:
                absence.state = "over"
            else:
                absence.state = "running"

    def _search_state(self, operator, value):
        """`state` is computed, so a plain search on it would be ignored.

        A stored compute would be wrong here: « en cours » changes with the
        clock, not with a write, so a stored value goes stale at midnight
        without anything touching the row.
        """
        if operator not in ("=", "!=", "in", "not in"):
            raise ValidationError(_("Filtre non pris en charge sur l'état."))
        wanted = value if isinstance(value, (list, tuple)) else [value]
        matching = self.with_context(active_test=False).search([]).filtered(
            lambda a: a.state in wanted)
        negative = operator in ("!=", "not in")
        return [("id", "not in" if negative else "in", matching.ids)]

    def _compute_log_count(self):
        counts = {}
        if self.ids:
            grouped = self.env["bf.email.auto.log"].sudo()._read_group(
                [("absence_id", "in", self.ids), ("state", "=", "sent")],
                ["absence_id"], ["__count"],
            )
            counts = {absence.id: n for absence, n in grouped}
        for absence in self:
            absence.log_count = counts.get(absence.id, 0)

    # ------------------------------------------------------------------
    # Validation
    # ------------------------------------------------------------------
    @api.constrains("is_template", "date_from", "date_to")
    def _check_period(self):
        for absence in self:
            if absence.is_template:
                if absence.date_from or absence.date_to:
                    raise ValidationError(_(
                        "Un message type n'a pas de dates : il sert de patron "
                        "à des absences qui, elles, en ont."))
                continue
            if not absence.date_from or not absence.date_to:
                raise ValidationError(_(
                    "Une absence a besoin d'une date de début et d'une date "
                    "de fin. Sans date de fin, personne ne l'éteint."))
            if absence.date_to <= absence.date_from:
                raise ValidationError(_(
                    "La fin de l'absence précède son début."))

    @api.constrains("cooldown_days")
    def _check_cooldown(self):
        for absence in self:
            if not absence.is_template and absence.cooldown_days < 1:
                raise ValidationError(_(
                    "Répondre plus d'une fois par jour au même expéditeur "
                    "contredit la RFC 3834, qui recommande sept jours. "
                    "Minimum accepté : 1."))

    @api.constrains("user_id", "date_from", "date_to", "is_template", "active")
    def _check_no_overlap(self):
        """Two live absences over the same instant would race for the reply."""
        for absence in self:
            if absence.is_template or not absence.active:
                continue
            clash = self.search([
                ("id", "!=", absence.id),
                ("user_id", "=", absence.user_id.id),
                ("is_template", "=", False),
                ("date_from", "<", absence.date_to),
                ("date_to", ">", absence.date_from),
            ], limit=1)
            if clash:
                raise ValidationError(_(
                    "Cette période chevauche « %(other)s » (%(start)s → "
                    "%(end)s). Deux absences actives au même instant se "
                    "disputeraient la réponse.",
                    other=clash.name, start=clash.date_from,
                    end=clash.date_to,
                ))

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------
    def action_end_now(self):
        """Stop an absence early without deleting its history."""
        now = fields.Datetime.now()
        for absence in self:
            if absence.is_template:
                continue
            absence.date_to = now if absence.date_from < now else absence.date_from
        return True

