"""bf.email.absence — le répondeur d'absence.

Odoo n'en a pas. Ni le cœur, ni l'OCA : `mail_autogenerated_header` fait
l'inverse (il marque NOTRE courrier sortant pour que les répondeurs des autres
se taisent), et `hr_holidays` sait qui est absent sans jamais l'écrire à
personne. Ce module-ci reçoit déjà le courrier et porte déjà les gardes du
réacheminement, alors c'est ici que ça vit.

**La RFC 3834 est le cahier des charges, pas une inspiration.** Un répondeur
qui répond une fois de trop crée une boucle avec le répondeur d'en face, et
deux serveurs se renvoient la balle jusqu'à ce qu'un humain débranche. Les
règles tenues ici, dans l'ordre où elles sont évaluées :

- jamais à un message portant `Auto-Submitted` autre que `no` (§2) ;
- jamais à une liste : en-tête `List-*`, ou `Precedence` valant
  `list` / `junk` / `bulk` (§3.1.8) ;
- jamais à un retour nul, ni à `MAILER-DAEMON`, `owner-*`, `*-request` — les
  adresses que les systèmes automatiques utilisent pour parler (§2) ;
- jamais si l'adresse du destinataire n'est pas explicitement dans `À` ou
  `Cc` : un message reçu en copie cachée ou par une liste ne me vise pas (§3.2) ;
- **une seule réponse par expéditeur** sur une fenêtre glissante, sept jours
  par défaut (§4.3). Comptée par personne, pas par période d'absence : deux
  absences bout à bout ne valent pas deux réponses au même correspondant ;
- la réponse porte `Auto-Submitted: auto-replied`, `In-Reply-To`,
  `References`, un objet préfixé `Auto:`, et **aucune pièce jointe** (§3).

Un écart assumé : la RFC recommande `text/plain`. On envoie du HTML bref,
parce que le corps est rédigé dans Odoo et qu'un lien de prise de rendez-vous
cliquable est la moitié de l'intérêt. Le reste du §3 est tenu.

Ce que la concurrence ne fait pas, et qui tient ici en réutilisant l'existant :
le message **dépend de qui écrit** (les conditions du moteur de règles, donc
« client » et « ce contact précis », pas seulement interne/externe), la relève
**route vraiment** la fiche vers la boîte du collègue, et la période peut
**s'allumer et s'éteindre depuis l'agenda** — parce que le vrai défaut d'un
répondeur n'est pas de mal répondre, c'est qu'on oublie de l'éteindre.
"""

import logging
import re
from datetime import timedelta

from odoo import _, api, fields, models
from odoo.exceptions import ValidationError
from odoo.tools import formataddr, html_escape

_logger = logging.getLogger(__name__)

# RFC 3834 §4.3 recommends seven days as the default.
DEFAULT_COOLDOWN_DAYS = 7
# A per-absence ceiling, for the day something goes wrong upstream.
DEFAULT_DAILY_CAP = 200

# Local-parts that belong to machinery, never to a person expecting an answer.
_ROBOT_LOCALPART = re.compile(
    r"^(mailer-daemon|postmaster|owner-|.*-request$|noreply|no-reply"
    r"|do-not-reply|donotreply|bounce|bounces|notification|notifications)",
    re.IGNORECASE,
)

# Default pattern for calendar-driven absences. Deliberately narrow: a false
# positive here turns the responder on while somebody is at their desk.
DEFAULT_CALENDAR_PATTERN = (
    r"(?i)\b(vacances?|cong[ée]s?|absence|absent[e]?|out\s*of\s*office|ooo"
    r"|f[ée]ri[ée]|sabbatique)\b"
)


