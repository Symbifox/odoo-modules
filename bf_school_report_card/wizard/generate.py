from odoo import _, fields, models
from odoo.exceptions import AccessError, UserError

from ..models.report_card import MANAGER


class ReportCardGenerate(models.TransientModel):
    """Make, or refresh, the draft report cards of a group for a term."""

    _name = "bf.school.report.card.generate"
    _description = "Generate the report cards of a group"

    group_id = fields.Many2one("bf.school.group", required=True)
    year_id = fields.Many2one(related="group_id.year_id")
    term_id = fields.Many2one("bf.school.term", required=True, domain="[('year_id', '=', year_id)]")
    lang = fields.Selection(
        lambda self: self.env["res.lang"].get_installed(), "Language", required=True,
        default=lambda self: self.env.company.partner_id.lang or "fr_CA")

    def action_generate(self):
        self.ensure_one()
        if not self.env.user.has_group(MANAGER):
            raise AccessError(_("Report cards are generated by the school administration."))
        cards = self.env["bf.school.report.card"]._generate(self.group_id, self.term_id, lang=self.lang)
        if not cards:
            raise UserError(_("Nothing to generate: every report card of this group and term is already issued."))
        return {
            "type": "ir.actions.act_window", "name": _("Report cards"), "res_model": "bf.school.report.card",
            "view_mode": "list,form", "domain": [("id", "in", cards.ids)]}


class ReportCardCorrect(models.TransientModel):
    """Why an issued report card is corrected."""

    _name = "bf.school.report.card.correct"
    _description = "Correct a report card"

    card_id = fields.Many2one("bf.school.report.card", required=True)
    reason = fields.Char(required=True)

    def action_correct(self):
        self.ensure_one()
        return self.card_id.with_context(correction_reason=self.reason).action_correct()
