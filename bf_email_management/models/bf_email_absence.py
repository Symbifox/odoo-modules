    # ------------------------------------------------------------------
    # The guards
    # ------------------------------------------------------------------
    def _blocked_reason(self, record):
        """Why this message must not be answered — or False to proceed.

        Every guard is answered **here**, before a mail.mail exists. An
        automatic reply already handed to the queue cannot be recalled by a
        rollback, and the one it loops with is somebody else's server.
        """
        self.ensure_one()
        Log = self.env["bf.email.auto.log"]
        headers = record.raw_headers or ""

        # Le mode test est refusé dans `_send`, pas ici : cette méthode répond
        # « pourquoi ce message est-il sans réponse », et tourner sous une
        # suite de tests n'est pas une propriété du message. Placée en tête,
        # la garde masquait toutes les autres et chaque test de garde lisait
        # « mode test » au lieu du motif qu'il vérifiait.
        if record.direction != "in":
            return "courriel sortant"
        if not record.email_from:
            return "aucun expéditeur"

        auto = re.search(r"^Auto-Submitted:\s*([^\r\n;]+)", headers,
                         re.IGNORECASE | re.MULTILINE)
        if auto and auto.group(1).strip().lower() != "no":
            return "message automatique (Auto-Submitted: %s)" % (
                auto.group(1).strip())

        if re.search(r"^List-(Id|Unsubscribe|Post|Help|Archive|Owner):",
                     headers, re.IGNORECASE | re.MULTILINE):
            return "message de liste (en-tête List-*)"

        precedence = re.search(r"^Precedence:\s*([^\r\n]+)", headers,
                               re.IGNORECASE | re.MULTILINE)
        if precedence and precedence.group(1).strip().lower() in (
                "list", "junk", "bulk"):
            return "Precedence: %s" % precedence.group(1).strip()

        return_path = re.search(r"^Return-Path:\s*<\s*>", headers,
                                re.IGNORECASE | re.MULTILINE)
        if return_path:
            return "retour nul (rebond ou notification de service)"

        sender = Log._normalize(record.email_from)
        local = sender.split("@", 1)[0] if "@" in sender else sender
        if _ROBOT_LOCALPART.match(local):
            return "adresse de service (%s)" % local

        if record.is_bulk:
            return "envoi de masse"

        # RFC 3834 §3.2: a valid address for the recipient must appear
        # explicitly in a recipient field. Bcc and list traffic are exactly
        # what this excludes, and they are the traffic that loops.
        if not (record.is_to_me or record.is_cc_to_me):
            return "je ne suis ni dans « À » ni dans « Cc »"

        own = self.env["bf.email"]._get_self_addresses(user=self.user_id)
        if sender in own:
            return "expéditeur = moi-même"

        cutoff = fields.Datetime.subtract(
            fields.Datetime.now(), days=max(1, self.cooldown_days))
        if Log._replied_since(self.user_id, record.email_from, cutoff):
            return "déjà répondu à cette adresse depuis %s jours" % (
                self.cooldown_days)

        cap = self._daily_cap()
        if cap and self._sent_today() >= cap:
            return "plafond quotidien atteint (%s)" % cap
        return False

    def _daily_cap(self):
        raw = self.env["ir.config_parameter"].sudo().get_param(
            "bf_email.absence_daily_cap")
        try:
            return max(0, int(raw)) if raw else DEFAULT_DAILY_CAP
        except ValueError:
            return DEFAULT_DAILY_CAP

    def _sent_today(self):
        self.ensure_one()
        start = fields.Datetime.now().replace(
            hour=0, minute=0, second=0, microsecond=0)
        return self.env["bf.email.auto.log"].sudo().search_count([
            ("absence_id", "=", self.id),
            ("kind", "=", "absence"),
            ("state", "=", "sent"),
            ("create_date", ">=", fields.Datetime.to_string(start)),
        ])

    # ------------------------------------------------------------------
    # Composing and sending
    # ------------------------------------------------------------------
    def _pick_reply(self, record, ctx=None):
        """The first message whose audience matches, else the default one."""
        self.ensure_one()
        default = self.env["bf.email.absence.reply"]
        for reply in self.reply_ids.sorted(lambda r: (r.sequence, r.id)):
            if not reply.condition_ids:
                default = default or reply
                continue
            if all(c._match(record, ctx) for c in reply.condition_ids):
                return reply
        return default

    def _target_lang(self, record):
        """Answer in the correspondent's language when Odoo knows it."""
        self.ensure_one()
        partner = record.partner_id or record.author_id
        return (partner.lang if partner and partner.lang
                else self.user_id.lang) or "en_US"

    def _placeholders(self, record):
        self.ensure_one()
        delegate = self.delegate_user_id
        back = fields.Datetime.context_timestamp(
            self, self.date_to) if self.date_to else None
        return {
            "{nom}": self.user_id.name or "",
            "{retour}": back.strftime("%d/%m/%Y") if back else "",
            "{releve}": delegate.name if delegate else "",
            "{releve_courriel}": (delegate.email or "") if delegate else "",
            "{motif}": self.name or "",
        }

    def _render_body(self, record, reply):
        """The message body, placeholders expanded, links appended."""
        self.ensure_one()
        lang = self._target_lang(record)
        body = reply.with_context(lang=lang).body_html or ""
        for token, value in self._placeholders(record).items():
            body = body.replace(token, html_escape(value))

        if self.include_booking_links:
            links = self._booking_links_html()
            if links:
                body += links
        return body

    def _booking_links_html(self):
        """The owner's signature quick links, when that module is installed.

        Read through the field registry rather than a manifest dependency:
        the signature module is optional, and a routing module has no business
        requiring a branding one.
        """
        self.ensure_one()
        user = self.user_id
        if "bf_signature_link_ids" not in user._fields:
            return ""
        try:
            links = user.sudo().bf_signature_link_ids
            if getattr(user, "bf_signature_use_company_links", False):
                links |= user.company_id.sudo().bf_signature_link_ids
        except Exception:
            return ""
        links = links.sorted(lambda link: (link.sequence, link.id))
        if not links:
            return ""
        items = "".join(
            '<li style="margin:2px 0;"><a href="%s" style="color:#3C6E9F;">'
            "%s%s</a></li>" % (
                html_escape(link.url),
                (html_escape(link.icon) + "&#160;") if link.icon else "",
                html_escape(link.name),
            )
            for link in links
        )
        return ('<ul style="margin:12px 0 0 0;padding-left:18px;'
                'font-size:13px;">%s</ul>' % items)

    def _send(self, record, ctx=None):
        """Answer ``record``. Returns the mail.mail, or an empty set."""
        self.ensure_one()
        Log = self.env["bf.email.auto.log"]

        if Log._test_mode():
            Log._log(record, record.email_from or "?", "skipped",
                     kind="absence", reason="mode test : aucun envoi",
                     absence=self)
            return self.env["mail.mail"]

        blocked = self._blocked_reason(record)
        if blocked:
            Log._log(record, record.email_from or "?", "skipped",
                     kind="absence", reason=blocked, absence=self)
            return self.env["mail.mail"]

        reply = self._pick_reply(record, ctx)
        if not reply:
            Log._log(record, record.email_from, "skipped", kind="absence",
                     reason="aucun message ne vise cet expéditeur",
                     absence=self)
            return self.env["mail.mail"]

        owner = self.user_id
        from_addr = (record.account_id.login or owner.email
                     or owner.partner_id.email)
        if not from_addr:
            Log._log(record, record.email_from, "error", kind="absence",
                     reason="aucune adresse d'expédition pour %s" % owner.name,
                     absence=self)
            return self.env["mail.mail"]

        subject = record.subject or _("(sans objet)")
        if not subject.lower().startswith("auto:"):
            subject = "Auto: %s" % subject

        headers = {
            # RFC 3834 §5: this is what stops the responder on the other side.
            "Auto-Submitted": "auto-replied",
            # Microsoft's equivalent, honoured by Exchange and Outlook.
            "X-Auto-Response-Suppress": "All",
            "X-BF-Absence": str(self.id),
        }
        if record.message_id_header:
            headers["In-Reply-To"] = record.message_id_header
            headers["References"] = record.message_id_header

        try:
            mail = self.env["mail.mail"].sudo().create({
                "subject": subject[:250],
                "body_html": self._render_body(record, reply),
                "email_from": formataddr((owner.name, from_addr)),
                "email_to": record.email_from,
                "headers": repr(headers),
                "auto_delete": True,
                # RFC 3834 §3.1.6: no attachments, and nothing of the
                # original message's non-text content comes back out.
                "attachment_ids": [(5, 0, 0)],
            })
        except Exception as exc:
            _logger.warning(
                "bf.email.absence %s: réponse impossible pour bf.email %s",
                self.id, record.id, exc_info=True,
            )
            Log._log(record, record.email_from, "error", kind="absence",
                     reason=str(exc), absence=self)
            return self.env["mail.mail"]

        Log._log(record, record.email_from, "sent", kind="absence",
                 mail=mail, absence=self)
        _logger.info(
            "bf.email.absence %s: réponse d'absence à %s (bf.email %s)",
            self.id, record.email_from, record.id,
        )

        if self.route_to_delegate and self.delegate_user_id:
            try:
                record.sudo().write(
                    {"user_id": self.delegate_user_id.id})
            except Exception:
                _logger.warning(
                    "bf.email.absence %s: fiche %s non confiée à la relève",
                    self.id, record.id, exc_info=True,
                )
        return mail

    # ------------------------------------------------------------------
    # Calendar-driven absences
    # ------------------------------------------------------------------
    @api.model
    def _calendar_pattern(self):
        raw = self.env["ir.config_parameter"].sudo().get_param(
            "bf_email.absence_calendar_pattern")
        return raw or DEFAULT_CALENDAR_PATTERN

    @api.model
    def _cron_sync_calendar(self):
        """Create, move and retire absences from the calendar.

        Only touches rows it created (`source='calendar'`). A period typed by
        hand is never moved by a cron: the person who typed it is the one who
        decides when it ends.
        """
        Users = self.env["res.users"].sudo()
        owners = Users.search([
            ("share", "=", False),
            ("bf_absence_from_calendar", "=", True),
        ])
        if not owners:
            return 0
        pattern = re.compile(self._calendar_pattern())
        horizon_from = fields.Datetime.subtract(fields.Datetime.now(), days=1)
        horizon_to = fields.Datetime.add(fields.Datetime.now(), days=180)
        touched = 0

        for user in owners:
            template = self.sudo().search([
                ("user_id", "=", user.id), ("is_template", "=", True),
            ], limit=1)
            if not template:
                _logger.info(
                    "bf.email.absence: %s a demandé la détection à l'agenda "
                    "mais n'a pas de message type — rien à copier.",
                    user.login,
                )
                continue

            events = self.env["calendar.event"].sudo().search([
                ("user_id", "=", user.id),
                ("start", "<=", fields.Datetime.to_string(horizon_to)),
                ("stop", ">=", fields.Datetime.to_string(horizon_from)),
            ])
            matching = events.filtered(lambda e: pattern.search(e.name or ""))
            touched += self._sync_user_calendar(user, template, matching)
        return touched

    def _sync_user_calendar(self, user, template, events):
        """One user's calendar-driven absences, reconciled with ``events``."""
        existing = self.sudo().with_context(active_test=False).search([
            ("user_id", "=", user.id),
            ("source", "=", "calendar"),
        ])
        by_event = {a.calendar_event_id.id: a for a in existing
                    if a.calendar_event_id}
        touched = 0

        for event in events:
            start, stop = self._event_window(event)
            absence = by_event.pop(event.id, None)
            if absence:
                vals = {}
                if absence.date_from != start:
                    vals["date_from"] = start
                if absence.date_to != stop:
                    vals["date_to"] = stop
                if not absence.active:
                    vals["active"] = True
                if vals:
                    absence.sudo().write(vals)
                    touched += 1
                    _logger.info(
                        "bf.email.absence %s: période reprise de l'agenda "
                        "(%s → %s)", absence.id, start, stop)
                continue
            created = self.sudo().create({
                "name": event.name or _("Absence"),
                "user_id": user.id,
                "company_id": user.company_id.id,
                "source": "calendar",
                "calendar_event_id": event.id,
                "date_from": start,
                "date_to": stop,
                "delegate_user_id": template.delegate_user_id.id,
                "route_to_delegate": template.route_to_delegate,
                "include_booking_links": template.include_booking_links,
                "cooldown_days": template.cooldown_days,
                "decline_meetings": template.decline_meetings,
                "reply_ids": [
                    (0, 0, reply._copy_vals()) for reply in template.reply_ids
                ],
            })
            touched += 1
            _logger.info(
                "bf.email.absence %s: créée depuis l'événement « %s » "
                "(%s → %s)", created.id, event.name, start, stop)

        # Events that no longer match — renamed, deleted, or moved out of the
        # horizon. Deactivate rather than delete: the journal points at them.
        for orphan in by_event.values():
            if orphan.active:
                orphan.sudo().write({"active": False})
                touched += 1
                _logger.info(
                    "bf.email.absence %s: désactivée, son événement d'agenda "
                    "a disparu", orphan.id)
        return touched

    @api.model
    def _event_window(self, event):
        """Start and end of an event, all-day convention included.

        Odoo stores an all-day event with both ends at 00:00:00 and a `stop`
        on the LAST day. Taken literally, a one-day absence would last zero
        second and never fire.
        """
        start, stop = event.start, event.stop
        if event.allday:
            stop = stop + timedelta(hours=23, minutes=59, seconds=59)
        return start, stop

    # ------------------------------------------------------------------
    # Declining meetings
    # ------------------------------------------------------------------
    @api.model
    def _cron_decline_meetings(self):
        """Decline the invitations that land inside a running absence.

        Narrow on purpose: it writes ONE field on the absent person's own
        attendee row, and only from « needs action ». It never touches the
        event, never removes an attendee, and never answers for anybody else —
        an automatic hand in somebody else's calendar is how a synchronisation
        turns into a data loss.
        """
        now = fields.Datetime.now()
        running = self.sudo().search([
            ("is_template", "=", False),
            ("decline_meetings", "=", True),
            ("date_from", "<=", fields.Datetime.to_string(now)),
            ("date_to", ">=", fields.Datetime.to_string(now)),
        ])
        declined = 0
        for absence in running:
            partner = absence.user_id.partner_id
            if not partner:
                continue
            attendees = self.env["calendar.attendee"].sudo().search([
                ("partner_id", "=", partner.id),
                ("state", "=", "needsAction"),
                ("event_id.start", ">=",
                 fields.Datetime.to_string(absence.date_from)),
                ("event_id.start", "<=",
                 fields.Datetime.to_string(absence.date_to)),
            ])
            # Never decline the event that created the absence.
            if absence.calendar_event_id:
                attendees = attendees.filtered(
                    lambda a: a.event_id != absence.calendar_event_id)
            if not attendees:
                continue
            attendees.write({"state": "declined"})
            declined += len(attendees)
            _logger.info(
                "bf.email.absence %s: %s invitation(s) refusée(s) pendant "
                "l'absence", absence.id, len(attendees),
            )
        return declined


